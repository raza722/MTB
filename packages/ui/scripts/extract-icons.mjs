// One-off: converts the MTB Campus design system's icon set (design-system-source/icons.bundle.js,
// cut from its components/bundle.js) into src/icons.tsx. Re-run if the design system's icons change.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../design-system-source/icons.bundle.js", import.meta.url), "utf8");
const start = src.indexOf("var paths = {");
const end = src.indexOf("function Icon(");
const body = src.slice(start, end);

const entries = [];
const keyRe = /^ {4}(\w+): /gm;
const keys = [...body.matchAll(keyRe)];
keys.forEach((m, i) => {
  const chunk = body.slice(m.index, i + 1 < keys.length ? keys[i + 1].index : body.length);
  const shapes = [...chunk.matchAll(/\.jsx\)\("(\w+)", \{([^}]*)\}\)/g)].map(([, tag, attrs]) => {
    const props = [...attrs.matchAll(/(\w+): "([^"]*)"/g)].map(([, k, v]) => `${k}="${v}"`).join(" ");
    return `<${tag} ${props} />`;
  });
  entries.push([m[1], shapes]);
});

const out = `// Generated by scripts/extract-icons.mjs from the MTB Campus design system. Do not edit.
// The system's own stroke icons: 24-unit grid, 1.75px stroke, round caps and joins.
import type { ReactElement, SVGAttributes } from "react";

const paths = {
${entries.map(([name, shapes]) => `  ${name}: (\n    <>\n      ${shapes.join("\n      ")}\n    </>\n  ),`).join("\n")}
} satisfies Record<string, ReactElement>;

export type IconName = keyof typeof paths;
export const ICON_NAMES = Object.keys(paths) as IconName[];

export interface IconProps extends Omit<SVGAttributes<SVGSVGElement>, "name"> {
  name: IconName;
  /** Pixel size; 18 in buttons, 20 elsewhere. */
  size?: number;
  /** Accessible name. Without it the icon is decorative (aria-hidden). */
  label?: string;
}

export function Icon({ name, size = 20, label, ...rest }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
      {...rest}
    >
      {paths[name]}
    </svg>
  );
}
`;

writeFileSync(new URL("../src/icons.tsx", import.meta.url), out);
console.log(`icons.tsx: ${entries.length} icons (${entries.filter(([, s]) => s.length === 0).map(([n]) => n).join(", ") || "none empty"})`);
