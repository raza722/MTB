/** The live notices (published, drafts and taken down), kept for the session. */
export const noticesStore = createStore<Notice[]>("notices", () => NOTICES.map((n) => ({ ...n })));

/**
 * Notices the portal should show a family: published, not expired, for this campus and (for class notices)
 * this child's class-section. Newest first, pinned ones on top.
 */
export function publishedNotices(campus: CampusCode, classSection: string | null = null, today = DEMO_TODAY): Notice[] {
  return noticesStore
    .get()
    .filter((n) => noticeVisibleTo(n, campus, classSection, today))
    .sort((a, b) => Number(Boolean(b.pinned)) - Number(Boolean(a.pinned)) || b.publishedAt.localeCompare(a.publishedAt));
}
