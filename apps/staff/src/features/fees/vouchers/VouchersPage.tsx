const STATUS_TONE: Record<FeeVoucherStatus, "unpaid" | "pending" | "paid" | "overdue" | "cancelled"> = {
  ISSUED: "unpaid",
  PART_PAID: "pending",
  PAID: "paid",
  OVERDUE: "overdue",
  CANCELLED: "cancelled",
};

export function VoucherStatusBadge({ status }: { status: FeeVoucherStatus }) {
  return <StatusBadge status={STATUS_TONE[status]}>{FEE_VOUCHER_STATUS_LABEL[status]}</StatusBadge>;
}

function RunRow({ run, i, onShow, showCampus }: { run: FeeVoucherRun; i: number; onShow: () => void; showCampus: boolean }) {
  const paid = run.counts.PAID;
  const live = run.count - run.counts.CANCELLED;
  const pct = live ? Math.round((paid / live) * 100) : 0;
  return (
    <li className="mtb-slide-in grid items-center gap-3 rounded-md border border-border bg-surface-raised px-4 py-3 md:grid-cols-[minmax(0,1.4fr)_minmax(0,1fr)_auto]" style={slide(i)}>
      <div className="grid min-w-0 gap-0.5">
        <span className="font-medium">
          {feeMonthLabel(run.month)} · {run.scope}
          {showCampus && <span className="text-ink-muted"> · {campusLabel(run.campus)}</span>}
        </span>
        <span className="truncate text-small text-ink-muted">
          {formatCount(run.count)} vouchers · due {formatDate(run.dueDate)} · generated by {run.generatedBy}, {formatDateTime(run.generatedAt)}
        </span>
      </div>
      <div className="grid gap-1">
        <div className="flex justify-between text-small">
          <span className="text-ink-muted">
            {formatCount(paid)} of {formatCount(live)} paid
            {run.counts.OVERDUE > 0 && <span className="text-status-overdue-ink"> · {formatCount(run.counts.OVERDUE)} overdue</span>}
          </span>
          <span className="tabular-nums">{formatRs(run.collected)}</span>
        </div>
        <span className="mtb-meter" role="progressbar" aria-valuenow={pct} aria-valuemin={0} aria-valuemax={100} aria-label={`${pct}% of vouchers paid`}>
          <span style={{ width: `${pct}%` }} />
        </span>
      </div>
      <div className="flex flex-wrap gap-2">
        <Button size="sm" icon="filter" onClick={onShow}>
          Show
        </Button>
        <Link to="/fees/vouchers/print" search={{ run: run.id }} className={buttonClassName({ size: "sm" })}>
          <Icon name="printer" size={16} />
          Print all
        </Link>
      </div>
    </li>
  );
}

function VoucherPanel({ voucherNo, onClose }: { voucherNo: string; onClose: () => void }) {
  const q = useQuery(feeSetupQueries.voucher(voucherNo));
  const toast = useToast();
  const queryClient = useQueryClient();
  const readOnly = useReadOnly();
  const canIssue = useCanAny(["fees.collect", "fees.setup"]);
  const canCollect = useCanAny(["fees.collect"]);
  const [cancelling, setCancelling] = useState(false);
  const [reason, setReason] = useState("");
  const [tried, setTried] = useState(false);
  const key = useMemo(() => newIdempotencyKey(), [voucherNo, cancelling]); // eslint-disable-line react-hooks/exhaustive-deps
  const v = q.data;
  const cancel = useMutation({
    mutationFn: () => feeSetupApi.cancelVoucher(voucherNo, reason, key),
    onSuccess: (r) => {
      toast({ title: `Voucher ${r.voucherNo} cancelled`, message: "Its charges stay on the student's ledger; issue a new voucher if needed." });
      void queryClient.invalidateQueries({ queryKey: ["fees", "setup"] });
      setCancelling(false);
    },
  });
  const print = () => {
    void feeSetupApi.markVouchersPrinted([voucherNo]);
    window.print();
  };
  return (
    <SidePanel
      open
      wide
      onClose={onClose}
      title={v ? `Voucher ${v.voucherNo}` : "Voucher"}
      description={v ? `${v.studentName} (${v.grNo}) · ${v.classSection} · ${feeMonthLabel(v.month)}` : undefined}
      footer={
        v ? (
          <>
            {canIssue && !readOnly && (v.status === "ISSUED" || v.status === "OVERDUE") ? (
              <Button variant="danger-quiet" icon="ban" onClick={() => setCancelling(true)}>
                Cancel voucher
              </Button>
            ) : (
              <span />
            )}
            <div className="flex flex-wrap gap-2">
              {canCollect && v.status !== "PAID" && v.status !== "CANCELLED" && !readOnly && (
                <Link to="/fees/counter" search={{ gr: v.grNo }} className={buttonClassName({})}>
                  <Icon name="fees" size={16} />
                  Record payment
                </Link>
              )}
              <Button variant="primary" icon="printer" onClick={print}>
                Print
              </Button>
            </div>
          </>
        ) : undefined
      }
    >
      {q.isLoading && <div className="h-96 animate-pulse rounded-md bg-surface-sunken" aria-busy="true" />}
      {q.error && <LoadError what="This voucher" error={q.error} onRetry={() => void q.refetch()} />}
      {v && (
        <div className="grid gap-5">
          <div className="flex flex-wrap items-center gap-2">
            <VoucherStatusBadge status={v.status} />
            {v.receiptNos.map((no) => (
              <Link key={no} to="/fees/receipts/$receiptNo" params={{ receiptNo: no }} className="text-small text-brand-ink underline-offset-2 hover:underline">
                Receipt {no}
              </Link>
            ))}
          </div>
          {v.status === "CANCELLED" && <Banner tone="neutral" title="This voucher was cancelled.">{v.cancelledReason}</Banner>}
          {v.changedSinceIssue && (
            <Banner tone="warning" title="A charge changed after this voucher was printed.">
              A concession, waiver or due-date change now applies. The counter uses the new figure; cancel this voucher and generate a new one before handing it out again.
            </Banner>
          )}
          {v.status === "OVERDUE" && (
            <Banner tone="warning" title={`Not paid by ${formatDate(v.dueDate)}.`}>
              Late fine has been running since {formatDate(v.dueDate)}. Today the family pays about {formatRs(v.fineTable.find((r) => r.upTo >= feeToday())?.amount ?? v.fineTable.at(-1)?.amount ?? v.payableByDue)}; the counter works out the exact figure.
            </Banner>
          )}
          <KeyValue
            items={[
              ["Pay by due date", formatRs(v.payableByDue)],
              ["Arrears on it", formatRs(v.lines.filter((l) => l.arrears).reduce((a, l) => a + l.amount, 0))],
              ["Bank", `${v.bank.bankName} · ${v.bank.accountNo}`],
              ["Printed", v.printCount === 0 ? "Not printed yet" : `${v.printCount} ${v.printCount === 1 ? "time" : "times"}`],
            ]}
          />
          <div className="fees-desk" style={{ ["--doc-zoom" as string]: 0.5 }}>
            <div className="fees-desk-zoom">
              <VoucherSheet voucher={v} />
            </div>
          </div>
          <div className="fees-print-only mtb-print-area fees-print-voucher">
            <PaperSize size="A4L" />
            <VoucherSheet voucher={v} />
          </div>
        </div>
      )}
      <ConfirmDialog
        open={cancelling}
        onClose={() => setCancelling(false)}
        onConfirm={() => {
          setTried(true);
          if (reason.trim()) cancel.mutate();
        }}
        tone="danger"
        icon="ban"
        title="Cancel this voucher?"
        message="The voucher number is never reused. The charges on it stay on the student's ledger and can go on a new voucher."
        confirmLabel="Cancel voucher"
        cancelLabel="Keep voucher"
        loading={cancel.isPending}
        loadingLabel="Cancelling…"
        {...(cancel.error ? { error: errorText(cancel.error) } : {})}
      >
        <Textarea label="Reason" required rows={3} value={reason} onChange={(e) => setReason(e.target.value)} placeholder="For example: printed with the wrong due date." error={tried && !reason.trim() ? "Say why the voucher is cancelled." : undefined} />
      </ConfirmDialog>
    </SidePanel>
  );
}

export function VouchersPage({ initialRun }: { initialRun?: string }) {
  const ctx = useCtx();
  const classList = useFeeClasses(ctx.campus);
  const readOnly = useReadOnly();
  const canIssue = useCanAny(["fees.collect", "fees.setup"]);
  const [runId, setRunId] = useState(initialRun ?? "");
  const [month, setMonth] = useState("");
  const [cls, setCls] = useState("");
  const [status, setStatus] = useState<FeeVoucherStatus | "">("");
  const [query, setQuery] = useState("");
  const [q, setQ] = useState("");
  const [page, setPage] = useState(1);
  const [open, setOpen] = useState<string | null>(null);

  useEffect(() => {
    const t = setTimeout(() => setQ(query.trim()), 250);
    return () => clearTimeout(t);
  }, [query]);
  useEffect(() => setPage(1), [runId, month, cls, status, q, ctx.campus, ctx.session]);

  const list = useQuery({ ...feeSetupQueries.vouchers(ctx, { runId, month, classShort: cls, status, q, page }), placeholderData: keepPreviousData });
  const d = list.data;
  const filtersOn = Boolean(runId || month || cls || status || q);

  const columns: Array<Column<FeeVoucher>> = [
    { key: "voucherNo", header: "Voucher", width: 170, render: (v) => <span className="mtb-num font-medium">{v.voucherNo}</span> },
    {
      key: "student",
      header: "Student",
      render: (v) => (
        <span className="grid">
          <span className="font-medium">{v.studentName}</span>
          <span className="text-small text-ink-muted">
            {v.grNo} · {v.relation} {v.father}
          </span>
        </span>
      ),
    },
    { key: "class", header: "Class", width: 80, render: (v) => v.classSection },
    { key: "month", header: "Month", width: 96, render: (v) => feeMonthLabel(v.month) },
    { key: "due", header: "Due", width: 116, render: (v) => <span className="mtb-num">{formatDate(v.dueDate)}</span> },
    { key: "amount", header: "Pay by due date", align: "right", width: 140, render: (v) => <span className="mtb-num">{formatRs(v.payableByDue)}</span> },
    { key: "status", header: "Status", width: 130, render: (v) => <VoucherStatusBadge status={v.status} /> },
  ];

  return (
    <RequirePermission permission="fees.view" page="fee vouchers">
      <Page>
        <PageHeader
          title="Fee vouchers"
          actions={
            canIssue && !readOnly ? (
              <Link to="/fees/vouchers/new" className={buttonClassName({ variant: "primary" })}>
                <Icon name="plus" size={18} />
                Generate vouchers
              </Link>
            ) : undefined
          }
        />
        <FeesNav />
        {readOnly && <Banner tone="info" title="Past session: read-only.">Vouchers from this session can be viewed and reprinted, not issued or cancelled.</Banner>}
        {list.isError && <LoadError what="Vouchers" error={list.error} onRetry={() => void list.refetch()} />}

        <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
          <StatCard label={month ? `Issued for ${feeMonthLabel(month)}` : "Vouchers issued"} icon="file" loading={list.isLoading} value={<AnimatedNumber value={d?.summary.issued ?? 0} format={formatCount} />} foot={`${formatRs(d?.summary.payable ?? 0)} payable by the due dates`} />
          <StatCard label="Paid" icon="checkCircle" loading={list.isLoading} value={<AnimatedNumber value={d?.summary.paid ?? 0} format={formatCount} />} foot={`${formatRs(d?.summary.collected ?? 0)} received`} meter={d && d.summary.issued ? (d.summary.paid / d.summary.issued) * 100 : 0} meterLabel="Share of vouchers paid" onClick={() => setStatus("PAID")} />
          <StatCard label="Overdue" icon="alertCircle" tone={(d?.summary.overdue ?? 0) > 0 ? "warning" : "neutral"} loading={list.isLoading} value={<AnimatedNumber value={d?.summary.overdue ?? 0} format={formatCount} />} foot={`${formatRs(d?.summary.overdueAmount ?? 0)} plus late fine`} onClick={() => setStatus("OVERDUE")} />
          <StatCard label="Voucher runs" icon="layers" loading={list.isLoading} value={<AnimatedNumber value={d?.runs.length ?? 0} format={formatCount} />} foot="Class or campus at a time" />
        </div>

        {d && d.runs.length > 0 && (
          <Panel id="voucher-runs" title="Voucher runs" description="Each time vouchers were generated for a class or the whole campus. Print a run again at any time." rise={1}>
            <ul className="m-0 grid list-none gap-2 p-0">
              {d.runs.slice(0, 6).map((r, i) => (
                <RunRow key={r.id} run={r} i={i} showCampus={ctx.campus === "ALL"} onShow={() => setRunId(r.id)} />
              ))}
            </ul>
          </Panel>
        )}

        <DataTable
          caption={`Fee vouchers, ${campusLabel(ctx.campus)}`}
          columns={columns}
          rows={d?.vouchers ?? []}
          rowKey="voucherNo"
          loading={list.isLoading}
          onRowClick={(v) => setOpen(v.voucherNo)}
          toolbar={
            <div className="flex w-full flex-wrap items-end gap-3">
              <div className="w-64">
                <Input aria-label="Search vouchers" placeholder="Name, G.R. or voucher number" icon="search" value={query} onChange={(e) => setQuery(e.target.value)} />
              </div>
              <div className="w-40">
                <Select aria-label="Month" value={month} onChange={(e) => setMonth(e.target.value)} options={[{ value: "", label: "Every month" }, ...(d?.months ?? []).map((m) => ({ value: m, label: feeMonthLabel(m) }))]} />
              </div>
              <div className="w-36">
                <Select aria-label="Class" value={cls} onChange={(e) => setCls(e.target.value)} options={[{ value: "", label: "Every class" }, ...classList.options]} />
              </div>
              <div className="w-40">
                <Select
                  aria-label="Status"
                  value={status}
                  onChange={(e) => setStatus(e.target.value as FeeVoucherStatus | "")}
                  options={[{ value: "", label: "Every status" }, ...(Object.keys(FEE_VOUCHER_STATUS_LABEL) as FeeVoucherStatus[]).map((s) => ({ value: s, label: FEE_VOUCHER_STATUS_LABEL[s] }))]}
                />
              </div>
              {runId && (
                <StatusBadge status="info" dot={false}>
                  One run only
                </StatusBadge>
              )}
              {filtersOn && (
                <Button
                  variant="quiet"
                  size="sm"
                  icon="x"
                  onClick={() => {
                    setRunId("");
                    setMonth("");
                    setCls("");
                    setStatus("");
                    setQuery("");
                  }}
                >
                  Clear filters
                </Button>
              )}
            </div>
          }
          empty={
            <EmptyState
              icon="file"
              title={filtersOn ? "No vouchers match" : `No vouchers for ${campusLabel(ctx.campus)} yet`}
              description={filtersOn ? "Clear the filters or search for something else." : "Generate vouchers for a class or the whole campus; parents pay them at the bank or the school office."}
              action={
                !filtersOn && canIssue && !readOnly ? (
                  <Link to="/fees/vouchers/new" className={buttonClassName({ variant: "primary" })}>
                    Generate vouchers
                  </Link>
                ) : undefined
              }
            />
          }
          pagination={d && d.total > d.pageSize ? <Pagination page={d.page} pageSize={d.pageSize} total={d.total} onPageChange={setPage} /> : undefined}
        />
        {open && <VoucherPanel voucherNo={open} onClose={() => setOpen(null)} />}
      </Page>
    </RequirePermission>
  );
}
