import { feeMonthLabel, feeSetupApi, feeSetupQueries, type FeeVoucher } from "@mtb/api";
import { formatCount, formatDateTime, formatRs } from "@mtb/domain";
import { Banner, Button, buttonClassName, EmptyState, Icon, Segmented, Select, Skeleton, useToast } from "@mtb/ui";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { Link } from "@tanstack/react-router";
import { useState } from "react";
import { Page, PageHeader, RequirePermission } from "../../../app/shell/page";
import { FeesNav, LoadError, PaperSize } from "../shared";
import { VoucherSheet } from "./VoucherSheet";

/** /fees/vouchers/print?run= — every voucher in a run, one A4 landscape sheet each, ready for the printer. */
export function PrintVouchersPage({ runId }: { runId: string }) {
  const q = useQuery(feeSetupQueries.printRun(runId));
  const toast = useToast();
  const queryClient = useQueryClient();
  const [which, setWhich] = useState<"UNPAID" | "ALL">("UNPAID");
  const [cls, setCls] = useState("");
  const all = q.data?.vouchers ?? [];
  const classes = [...new Set(all.map((v) => v.classSection))].sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
  const shown: FeeVoucher[] = all.filter((v) => v.status !== "CANCELLED").filter((v) => which === "ALL" || v.status !== "PAID").filter((v) => !cls || v.classSection === cls);

  const print = () => {
    window.print();
    void feeSetupApi.markVouchersPrinted(shown.map((v) => v.voucherNo)).then(() => queryClient.invalidateQueries({ queryKey: ["fees", "setup"] }));
    toast({ title: `${formatCount(shown.length)} vouchers sent to the printer`, message: "Choose A4, landscape. Each sheet has the bank, school and parent copies." });
  };

  return (
    <RequirePermission permission="fees.view" page="voucher printing">
      <Page>
        <PageHeader
          title="Print vouchers"
          context={q.data ? `${feeMonthLabel(q.data.run.month)} · ${q.data.run.scope} · generated by ${q.data.run.generatedBy}, ${formatDateTime(q.data.run.generatedAt)}` : undefined}
          actions={
            <>
              <Link to="/fees/vouchers" className={buttonClassName({})}>
                <Icon name="arrowLeft" size={16} />
                Back to vouchers
              </Link>
              <Button variant="primary" icon="printer" onClick={print} disabled={shown.length === 0}>
                Print {formatCount(shown.length)}
              </Button>
            </>
          }
        />
        <FeesNav />
        {!runId && (
          <div className="mtb-card">
            <EmptyState icon="printer" title="Choose a voucher run to print" description="Open Vouchers and choose Print all beside a run." />
          </div>
        )}
        {q.isLoading && runId && <Skeleton height={420} />}
        {q.error && <LoadError what="This run" error={q.error} onRetry={() => void q.refetch()} />}
        {q.data && (
          <>
            <div className="flex flex-wrap items-end gap-3">
              <Segmented aria-label="Vouchers to print" value={which} onChange={(v) => setWhich(v as "UNPAID" | "ALL")} options={[{ value: "UNPAID", label: "Not yet paid" }, { value: "ALL", label: "All in the run" }]} />
              <div className="w-40">
                <Select aria-label="Class" value={cls} onChange={(e) => setCls(e.target.value)} options={[{ value: "", label: "Every class" }, ...classes.map((c) => ({ value: c, label: c }))]} />
              </div>
              <span className="text-small text-ink-muted">
                {formatCount(shown.length)} of {formatCount(all.length)} vouchers · {formatRs(shown.reduce((a, v) => a + v.payableByDue, 0))} payable
              </span>
            </div>
            {shown.length === 0 ? (
              <div className="mtb-card">
                <EmptyState icon="checkCircle" title="Nothing left to print" description="Every voucher in this choice is paid or cancelled. Choose All in the run to reprint them." />
              </div>
            ) : (
              <>
                {shown.length > 30 && <Banner tone="info">Showing the first 30 on screen; all {formatCount(shown.length)} print.</Banner>}
                <div className="fees-desk">
                  <div className="fees-desk-zoom">
                    {shown.slice(0, 30).map((v) => (
                      <VoucherSheet key={v.voucherNo} voucher={v} />
                    ))}
                  </div>
                </div>
                <div className="fees-print-only mtb-print-area fees-print-voucher">
                  <PaperSize size="A4L" />
                  {shown.map((v) => (
                    <VoucherSheet key={v.voucherNo} voucher={v} />
                  ))}
                </div>
              </>
            )}
          </>
        )}
      </Page>
    </RequirePermission>
  );
}
